/// A small deterministic smoke run (12 points per op) that runs in the
/// default suite — fast enough for `cargo test --workspace`, seeded the same
/// way, and exercising every operation.
#[test]
fn kill_test_smoke_all_ops() {
    for (op, seed) in [
        ("split", 0x5E1D_0601_0000_0001u64),
        ("rotate-incremental", 0x5E1D_0602_0000_0002),
        ("compress", 0x5E1D_0603_0000_0003),
    ] {
        let fix = fixture(op, op);
        let output_len = fix.expected_output.as_ref().map_or(usize::MAX, Vec::len);
        let points = kill_points(seed ^ 0x50, output_len, 12);
        for point in &points {
            std::fs::write(&fix.output, &fix.source).expect("reset destination");
            let status = run_child(op, &fix, point);
            let killed = !status.success();
            match op {
                "rotate-incremental" => assert_incremental_property(&fix, point, killed),
                _ => assert_rewrite_property(op, &fix, point, killed),
            }
        }
        std::fs::remove_dir_all(&fix.dir).ok();
    }
}
