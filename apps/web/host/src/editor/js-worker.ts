/**
 * Worker bootstrap for the browser form-script sandbox (SL-5.JS.01, ADR-P0020).
 *
 * The browser already has an engine — we do NOT compile one to WASM. Instead a
 * fresh Worker realm is created, every network/host capability is removed, and
 * ONLY the Acrobat calculation/format subset is installed. The host terminates
 * the Worker on a hard deadline; this module describes that realm and its
 * narrow postMessage protocol. It carries field values/options only — never
 * document bytes, URLs or host handles.
 */

/** Property used by the host to hand the request to the worker. */
export const WORKER_REQUEST_KEY = "__SLJS_REQUEST__";

/** Property used by the host (or tests) to receive the result. */
export const WORKER_SEND_KEY = "__SLJS_SEND__";

/** The only event types a form script may handle. */
export type SandboxEventType = "calculate" | "validate" | "format";

/** A field visible through `this.getField(name)` inside the worker. */
export interface SandboxField {
	readonly name: string;
	readonly value: string;
}

/** The narrow request — script text + field values + event descriptor only. */
export interface SandboxRequest {
	readonly script: string;
	readonly event: {
		readonly type: SandboxEventType;
		readonly targetName: string;
		readonly value: string;
	};
	readonly fields: readonly SandboxField[];
}

/** The narrow response — values only, no document bytes. */
export type SandboxResponse =
	| {
			readonly ok: true;
			readonly eventValue: string;
			readonly eventRc: boolean;
			readonly updates: readonly SandboxField[];
	  }
	| {
			readonly ok: false;
			readonly code: "js-script-rejected" | "js-runtime-error";
	  };

/**
 * Build the self-contained Worker bootstrap source.
 *
 * The dangerous globals are made non-writable, non-configurable `undefined`
 * AFTER a private reference to the send function is captured, so a script
 * cannot restore them and cannot message the host. The Acrobat API is installed
 * on the global object; `this` at the top level of a sloppy-mode script is that
 * same global, so `this.getField(name)` resolves. The script is evaluated with
 * indirect `eval` inside an IIFE, so it cannot reach the captured sender.
 */
export function buildWorkerBootstrap(): string {
	return `/*
 * Selis form-script sandbox bootstrap (SL-5.JS.01). Generated by js-worker.ts.
 * No imports, no network, no host handles — the narrow protocol only.
 */
(function () {
  "use strict";
  var __self = (typeof self !== "undefined") ? self : globalThis;
  var __send = __self.__SLJS_SEND__ ||
    (typeof __self.postMessage === "function" ? __self.postMessage.bind(__self) : null);

  var __denied = [
    "fetch", "XMLHttpRequest", "WebSocket", "EventSource", "importScripts",
    "WebAssembly", "indexedDB", "caches", "postMessage", "Worker",
    "SharedWorker", "ServiceWorker", "Notification", "navigator",
    "location", "origin"
  ];
  for (var d = 0; d < __denied.length; d++) {
    try {
      Object.defineProperty(__self, __denied[d], {
        value: undefined, writable: false, configurable: false
      });
    } catch (e) { /* a non-configurable host property: leaving it is safe */ }
  }

  function __fail(code) {
    if (__send) __send({ ok: false, code: code });
    else throw new Error(code);
  }

  var __req = __self.__SLJS_REQUEST__;
  if (!__req || typeof __req.script !== "string") {
    __fail("js-script-rejected");
    return;
  }

  try {
    var __fields = {};
    for (var f = 0; f < __req.fields.length; f++) {
      var rec = __req.fields[f];
      __fields[String(rec.name)] = { name: String(rec.name), value: String(rec.value) };
    }
    function __coerce(v) {
      return v === undefined || v === null ? "" : String(v);
    }
    function __getField(name) {
      var key = String(name);
      if (!Object.prototype.hasOwnProperty.call(__fields, key)) return null;
      var field = __fields[key];
      return {
        name: field.name,
        get value() { return field.value; },
        set value(v) { field.value = __coerce(v); }
      };
    }
    var __event = {
      type: String(__req.event.type),
      targetName: String(__req.event.targetName),
      value: __coerce(__req.event.value),
      rc: true
    };
    function __printf(fmt) {
      var args = Array.prototype.slice.call(arguments, 1);
      var out = "", i = 0, ai = 0;
      var s = String(fmt);
      while (i < s.length) {
        if (s.charAt(i) !== "%") { out += s.charAt(i); i++; continue; }
        if (s.charAt(i + 1) === "%") { out += "%"; i += 2; continue; }
        var j = i + 1;
        while (j < s.length && s.charAt(j) !== "s" && s.charAt(j) !== "d" &&
               s.charAt(j) !== "i" && s.charAt(j) !== "f" && s.charAt(j) !== "%") {
          j++;
        }
        if (j >= s.length || s.charAt(j) === "%") { out += "%"; i++; continue; }
        var spec = s.charAt(j), val = args[ai++];
        if (spec === "s") out += String(val);
        else if (spec === "d" || spec === "i") out += String(Math.trunc(Number(val)));
        else if (spec === "f") {
          var flag = s.slice(i + 1, j), dot = flag.indexOf(".");
          var precision = dot >= 0 ? parseInt(flag.slice(dot + 1), 10) : 6;
          out += Number(val).toFixed(Math.min(isNaN(precision) ? 6 : precision, 12));
        }
        i = j + 1;
      }
      return out;
    }
    function __printd(fmt, date) {
      var parts = String(date).split(/[-T:]/);
      return String(fmt)
        .replace(/yyyy/g, parts[0] || "")
        .replace(/mm/g, parts[1] || "")
        .replace(/dd/g, parts[2] || "");
    }
    __self.event = __event;
    __self.getField = __getField;
    __self.util = { printf: __printf, printd: __printd };
    var __af = [
      "AFNumber_Format", "AFNumber_Keystroke", "AFPercent_Format",
      "AFPercent_Keystroke", "AFDate_FormatEx", "AFDate_KeystrokeEx",
      "AFRange_Validate", "AFSimple_Validate"
    ];
    for (var a = 0; a < __af.length; a++) {
      __self[__af[a]] = function () { return undefined; };
    }

    (0, eval)(__req.script);

    var __updates = [];
    for (var u = 0; u < __req.fields.length; u++) {
      var original = __req.fields[u];
      var current = __fields[String(original.name)];
      if (current && current.value !== String(original.value)) {
        __updates.push({ name: current.name, value: current.value });
      }
    }
    if (__send) {
      __send({
        ok: true,
        eventValue: __coerce(__event.value),
        eventRc: !!__event.rc,
        updates: __updates
      });
    }
  } catch (err) {
    __fail("js-runtime-error");
  }
})();
`;
}

