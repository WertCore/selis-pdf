/**
 * Build the closed third-party vendor bundle (SL-4.UI.14 stage 3).
 *
 * The web host serves `apps/ui`'s own modules as native `tsc` ESM. React and
 * Radix are the exception the stage 3 proposal records: React/ReactDOM are
 * CommonJS, and every Radix package imports its siblings by bare name, so a
 * browser cannot load the closure without a resolver. This script bundles only
 * the curated surface in `src/chrome/vendor.ts`; the app's chrome modules stay
 * reviewable `tsc` output, and `place-assets.mjs` rewrites exactly four bare
 * specifiers to this file.
 *
 * The audit is part of the build, not a later review habit:
 *   - every input is on the pinned allow-list in `allowedInput`;
 *   - the output has no unresolved import and no remote code/`eval`;
 *   - the output stays under a size budget, so a wertkit change that quietly
 *     pulls the world fails here rather than at the browser's cold start.
 *
 * `dist/` is gitignored. The committed artefacts are the pins in
 * `package.json`/`pnpm-lock.yaml`, this script, and the curated entry.
 */

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build } from "esbuild";

const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outdir = resolve(appRoot, "dist/vendor");
const outfile = resolve(outdir, "vendor.js");
const metafilePath = resolve(outdir, "vendor.meta.json");
const cssTarget = resolve(outdir, "wertkit.css");
const require = createRequire(import.meta.url);

/** The largest uncompressed vendor file we are willing to review by eye. */
const SIZE_BUDGET = 3_000_000;

/**
 * Every source esbuild may read. The paths are pnpm's content-addressed store
 * paths, so a version change that introduces a new package fails the allow-list
 * instead of silently joining the bundle.
 */
function allowedInput(path) {
	const normalised = path.split("\\").join("/");
	return (
		normalised === "src/chrome/vendor.ts" ||
		normalised.includes("/node_modules/.pnpm/react@19.3.1/") ||
		normalised.includes("/node_modules/.pnpm/react-dom@19.3.1") ||
		normalised.includes("/node_modules/.pnpm/scheduler@") ||
		normalised.includes("/node_modules/.pnpm/@wertkit+ui@0.1.8") ||
		normalised.includes("/node_modules/.pnpm/@radix-ui+") ||
		normalised.includes("/node_modules/.pnpm/@floating-ui+") ||
		normalised.includes("/node_modules/.pnpm/detect-node-es@") ||
		normalised.includes("/node_modules/.pnpm/get-nonce@") ||
		normalised.includes("/node_modules/.pnpm/react-remove-scroll@") ||
		normalised.includes("/node_modules/.pnpm/react-remove-scroll-bar@") ||
		normalised.includes("/node_modules/.pnpm/react-style-singleton@") ||
		normalised.includes("/node_modules/.pnpm/use-callback-ref@") ||
		normalised.includes("/node_modules/.pnpm/use-sidecar@") ||
		normalised.includes("/node_modules/.pnpm/aria-hidden@") ||
		normalised.includes("/node_modules/.pnpm/tslib@")
	);
}

function withoutComments(source) {
	return source
		.replace(/\/\*[\s\S]*?\*\//g, "")
		.replace(/\/\/[^\n]*/g, "");
}

function assertBundleShape(source) {
	const code = withoutComments(source);
	const bareImports = [];
	for (const match of code.matchAll(/\bfrom\s*["']([^"']+)["']/g)) {
		const specifier = match[1];
		if (!specifier.startsWith(".") && !specifier.startsWith("/")) {
			bareImports.push(specifier);
		}
	}
	if (bareImports.length > 0) {
		throw new Error(`vendor.js has unresolved imports: ${bareImports.join(", ")}`);
	}
	if (/\bhttps?:\/\//.test(code)) {
		throw new Error("vendor.js contains a remote URL outside a comment");
	}
	if (/\beval\s*\(/.test(code) || /\bnew\s+Function\s*\(/.test(code)) {
		throw new Error("vendor.js contains eval or new Function");
	}
	if (/\bdocument\.write\s*\(/.test(code)) {
		throw new Error("vendor.js contains document.write");
	}
}

mkdirSync(outdir, { recursive: true });

const result = await build({
	absWorkingDir: appRoot,
	entryPoints: ["src/chrome/vendor.ts"],
	outfile,
	bundle: true,
	format: "esm",
	platform: "browser",
	target: ["es2022"],
	jsx: "automatic",
	define: {
		"process.env.NODE_ENV": '"production"',
	},
	minify: false,
	sourcemap: false,
	legalComments: "eof",
	metafile: true,
	banner: {
		js: "/* Generated by apps/ui/tools/build-vendor.mjs - do not edit. Sources are pinned by pnpm-lock.yaml. */",
	},
	logLevel: "warning",
});

const inputs = Object.keys(result.metafile.inputs);
const unexpected = inputs.filter((path) => !allowedInput(path));
if (unexpected.length > 0) {
	throw new Error(
		`vendor bundle read unexpected inputs (extend the allow-list deliberately):\n${unexpected.join("\n")}`,
	);
}

const source = readFileSync(outfile, "utf8");
assertBundleShape(source);
const bytes = Buffer.byteLength(source);
if (bytes > SIZE_BUDGET) {
	throw new Error(`vendor.js is ${bytes} bytes, over the ${SIZE_BUDGET}-byte review budget`);
}

writeFileSync(metafilePath, `${JSON.stringify(result.metafile, null, 2)}\n`, "utf8");
copyFileSync(require.resolve("@wertkit/ui/styles.css"), cssTarget);

// The browser can only import what this file exports. Check the built module
// itself, not just the source entry: a tree-shaking or re-export change that
// drops a name fails here, while the source still type-checks.
const expectedExports = [
	"AppShell",
	"Button",
	"Checkbox",
	"Dialog",
	"DialogClose",
	"Fragment",
	"Menu",
	"MenuItem",
	"MenuLabel",
	"MenuSeparator",
	"Select",
	"SelectGroup",
	"SelectItem",
	"StrictMode",
	"Suspense",
	"Switch",
	"Tabs",
	"TabsContent",
	"TabsList",
	"TabsTrigger",
	"ToastProvider",
	"Tooltip",
	"TooltipProvider",
	"createContext",
	"createElement",
	"createRoot",
	"forwardRef",
	"jsx",
	"jsxs",
	"memo",
	"useCallback",
	"useContext",
	"useEffect",
	"useId",
	"useLayoutEffect",
	"useMemo",
	"useReducer",
	"useRef",
	"useState",
	"useSyncExternalStore",
	"useToast",
];
const bundle = await import(pathToFileURL(outfile).href);
const missingExports = expectedExports.filter((name) => !(name in bundle));
if (missingExports.length > 0) {
	throw new Error(`vendor.js is missing curated exports: ${missingExports.join(", ")}`);
}

console.log(
	`build-vendor: ${inputs.length} inputs -> ${bytes} B vendor.js, ` +
		`${readFileSync(cssTarget).length} B wertkit.css`,
);
